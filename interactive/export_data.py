"""Export validated simulator data for the in-browser explorer -> interactive/data.js

Periodic orbits (CR3BP, differential correction), Lagrange points, NRLMSIS
orbit-mean densities and the sail/spacecraft catalogues come from the Python
simulator so that the JavaScript engine uses identical inputs.
"""
import json, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "simulator"))
from cislunar_sail import cr3bp as CR, sail as S
from cislunar_sail.constants import L_EM_KM, T_EM_S, DAY_S
from cislunar_sail.environment import density_table
from cislunar_sail.designs import HERITAGE, STUDY


def orbit_entry(key, label, o, n=600):
    t, X = o.sample(n)
    return {"key": key, "label": label, "period": o.period, "period_days": o.period_days(), "C": o.C,
            "stability": o.stability_index(), "states": np.round(X[:-1], 8).tolist()}


orbits = [
    orbit_entry("DRO", "Distant retrograde orbit (70,000 km)", CR.dro(70000)),
    orbit_entry("L1H", "EML1 northern halo (Az 15,000 km)", CR.halo(15000, 1, True)),
    orbit_entry("L2H", "EML2 halo (Az 10,000 km)", CR.halo(10000, 2, False)),
    orbit_entry("NRHO", "9:2 NRHO (Gateway-class)", CR.nrho()),
]
Lp = {k: v.tolist() for k, v in CR.lagrange_points().items()}
Cl = {k: float(CR.jacobi(np.r_[v, 0, 0, 0])) for k, v in CR.lagrange_points().items()}

dens = {}
for f in (70.0, 150.0, 230.0):
    h, lst, rho = density_table(f)
    dens[str(int(f))] = np.round(np.log(rho.mean(axis=1)), 5).tolist()
dens["alt"] = h.tolist()
# full altitude x local-solar-time tables (ln rho, kg/m^3) for the in-browser drag model
dens_lst = {"alt": h.tolist(), "lst": lst.tolist()}
for f in (70.0, 150.0, 230.0):
    _, _, rho = density_table(f)
    dens_lst[str(int(f))] = [[round(float(v), 3) for v in row] for row in np.log(rho)]

def face(fo):
    return {"r": fo.r, "s": fo.s, "ef": fo.eps_f, "eb": fo.eps_b, "Bf": fo.B_f, "Bb": fo.B_b}

films = {}
for key, m in (("AL_CP1", S.AL_CP1), ("AL_PEN_CR", S.AL_PEN_CR), ("AL_MYLAR", S.AL_MYLAR), ("AL_AL_CP1", S.AL_AL_CP1),
               ("CP1_THIN", S.CP1_THIN), ("IDEAL", S.IDEAL)):
    films[key] = {"name": m.name, "front": face(m.front), "back": face(m.back), "areal_gm2": m.areal_density_gm2}

presets = {}
for d in HERITAGE + STUDY:
    fk = [k for k, v in (("AL_CP1", S.AL_CP1), ("AL_PEN_CR", S.AL_PEN_CR), ("AL_MYLAR", S.AL_MYLAR), ("CP1_THIN", S.CP1_THIN)) if v is d.material][0]
    presets[d.key] = {"name": d.name, "mass": d.mass_kg, "area": d.area_m2, "film": fk, "sep_mN": d.sep_thrust_mN,
                      "isp": d.isp_s or 1500.0, "prop": d.propellant_kg, "gimbal": d.gimbal_deg or 30.0}

data = {"mu": CR.MU, "L_km": L_EM_KM, "T_s": T_EM_S, "orbits": orbits, "lagrange": Lp, "C_lagrange": Cl,
        "density_log": dens, "density_lst": dens_lst, "films": films, "presets": presets,
        "coast_days": {"L1H": 14.0, "L2H": 14.0, "NRHO": 10.0, "DRO": 20.0, "L4": 45.0, "L5": 45.0}}
with open(os.path.join(HERE, "data.js"), "w") as fh:
    fh.write("/* Generated by export_data.py from the validated Python simulator. Do not edit. */\n")
    fh.write("var SAIL_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
    fh.write("if (typeof module !== 'undefined') module.exports = SAIL_DATA;\n")
print("orbits:", [(o["key"], round(o["C"], 4), round(o["period_days"], 2)) for o in orbits])
print("size KB:", os.path.getsize(os.path.join(HERE, "data.js")) / 1024)
